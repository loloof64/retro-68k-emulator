export function drawChar(memory: Memory, code: number, x: number, y: number, color: number): void {
  const glyph = GLYPHS[code - 0x20]
  if (!glyph) return
  // The framebuffer is directly followed by the input registers, so an
  // out-of-range write would silently corrupt them instead of faulting.
  if (x < 0 || y < 0 || x + GLYPH_SIZE > FRAMEBUFFER_WIDTH || y + GLYPH_SIZE > FRAMEBUFFER_HEIGHT) {
    throw new Error(`Text out of screen bounds at (${x}, ${y})`)
  }
  for (let row = 0; row < GLYPH_SIZE; row++) {
    for (let col = 0; col < GLYPH_SIZE; col++) {
      if (glyph[row] & (1 << col)) {
        const pixel = (y + row) * FRAMEBUFFER_WIDTH + x + col
        memory.write32(FRAMEBUFFER_START + pixel * FRAMEBUFFER_BYTES_PER_PIXEL, color)
      }
    }
  }
}

// Walks a null-terminated string at `address`. '\n' goes to the next line
// (x back to 0); a glyph that would overflow the right edge wraps first.
// Transparent background; no scrolling (past the bottom -> throws).
export function drawString(memory: Memory, address: number, x: number, y: number, color: number): void {
  for (let byte = memory.read8(address++); byte !== 0; byte = memory.read8(address++)) {
    if (byte === 0x0a) {
      x = 0
      y += GLYPH_SIZE
      continue
    }
    if (x + GLYPH_SIZE > FRAMEBUFFER_WIDTH) {
      x = 0
      y += GLYPH_SIZE
    }
    drawChar(memory, byte, x, y, color)
    x += GLYPH_SIZE
  }
}
